package basic2026;


public class ArithmeticOperators {
    public static void main(String[] args) {
        int a = 20, b = 6;

        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);
    }
}
